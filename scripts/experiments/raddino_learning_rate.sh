#!/usr/bin/env bash
# RAD-DINO fine-tuning learning-rate check (post-hoc sensitivity analysis; the pre-specified arm stays).
# The pre-specified arm reused the CNN settings (encoder lr 7.55e-4 x 0.129 ~ 1e-4, high for a ViT).
# Grid: head lr {3e-4, 7.55e-4} x encoder lr {1e-5, 3e-5}, 2 seeds each, Shenzhen -> Montgomery
# protocol. Selection uses SHENZHEN VALIDATION ONLY: highest mean val AUROC; within 0.002 the lower
# mean val Brier score wins. Then the winner runs 5 seeds (NLM protocol) and 3 seeds (multi-site).
set -uo pipefail
cd "$(dirname "$0")/../.."
export PATH="$HOME/.local/bin:$PATH"
R="$HOME/tbmxai_runs/transfer/raddino_lr"
G=configs/transfer/raddino_lr
mkdir -p "$G" "$R"
step() { local name="$1"; shift; echo "=== $(date -u +%H:%M) START $name"; if "$@"; then echo "=== $(date -u +%H:%M) OK $name"; else echo "=== $(date -u +%H:%M) FAILED $name"; fi; }
uv run python - "$G" <<'PY'
import sys, yaml
from pathlib import Path
out = Path(sys.argv[1])
for base, stem in (("configs/transfer/nlm_raddino.yaml", "nlm"), ("configs/transfer/multisite_raddino_from_shenzhen.yaml", "multisite")):
    cfg = yaml.safe_load(open(base))
    for head in (3e-4, 7.55e-4):
        for enc in (1e-5, 3e-5):
            c = yaml.safe_load(yaml.safe_dump(cfg, sort_keys=False))
            c["name"] = f"{cfg['name']}_h{head:g}_e{enc:g}"
            c["training"]["optimizer"]["lr"] = head
            c["training"]["optimizer"]["encoder_lr_mult"] = round(enc / head, 6)
            (out / f"{stem}_h{head:g}_e{enc:g}.yaml").write_text(
                f"# generated by scripts/experiments/raddino_learning_rate.sh from {base}\n" + yaml.safe_dump(c, sort_keys=False))
PY
for f in "$G"/nlm_h*.yaml; do
  tag=$(basename "$f" .yaml)
  step "grid $tag" uv run tbmxai cv "$f" --folds 0 --seed 1 --seed 2 --output-dir "$R/grid/$tag"
done
best=$(uv run python - "$R/grid" <<'PY'
import sys, json, glob
from pathlib import Path
rows = []
for d in sorted(Path(sys.argv[1]).iterdir()):
    v = [json.load(open(m))["evaluation"]["val"]["metrics"] for m in glob.glob(f"{d}/seed*/metrics.json")]
    if len(v) == 2:
        rows.append((sum(x["auroc"]["value"] for x in v) / 2, -sum(x["brier"]["value"] for x in v) / 2, d.name))
ref = [json.load(open(m))["evaluation"]["val"]["metrics"]["auroc"]["value"]
       for m in sorted(glob.glob(str(Path.home() / "tbmxai_runs/transfer/nlm_raddino/seed[12]/metrics.json")))]
rows.sort(reverse=True)
top = rows[0]
close = [r for r in rows if top[0] - r[0] <= 0.002]
pick = max(close, key=lambda r: r[1])
log = {"grid": [{"config": r[2], "val_auroc": r[0], "neg_val_brier": r[1]} for r in rows],
       "registered_arm_val_auroc_seeds_1_2": ref, "selected": pick[2]}
(Path(sys.argv[1]).parent / "selection.json").write_text(json.dumps(log, indent=2))
print(pick[2].removeprefix("nlm_"))
PY
)
echo "selected: $best"
step "final nlm $best" uv run tbmxai cv "$G/nlm_$best.yaml" --folds 0 --seed 1 --seed 2 --seed 3 --seed 4 --seed 5 --output-dir "$R/nlm_$best"
step "final multisite $best" uv run tbmxai cv "$G/multisite_$best.yaml" --folds 0 --seed 1 --seed 2 --seed 3 --output-dir "$R/multisite_$best"
echo "=== $(date -u +%H:%M) raddino_learning_rate done"
